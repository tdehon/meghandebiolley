"use strict";

/* "Quel soin est fait pour moi ?" — runs entirely in the browser, nothing is stored or sent.
   Questions, labels and treatments come from the JSON block #quiz-data (generated by _outils/build.py). */

(() => {
  const root = document.querySelector("[data-quiz]");
  const dataEl = document.getElementById("quiz-data");
  if (!root || !dataEl) return;

  const data = JSON.parse(dataEl.textContent);
  const T = data.text;
  const answers = {};
  const history = []; // keys answered by the visitor, in order (for the Back button)

  /* Which question comes next, given the answers so far. */
  function nextQuestion() {
    if (!answers.reason) return "reason";
    if (answers.reason === "legs") return null;
    if (!answers.zone) return "zone";
    if (!answers.time) return "time";
    if (!answers.sound) return "sound";
    return null;
  }

  /* Total number of questions for this visitor's path (for "Question n of N"). */
  function totalQuestions() {
    if (answers.reason === "legs") return 1;
    if (answers.reason === "face") return 3;
    return 4;
  }

  /* Recommendation rules, based on Meghan's treatment descriptions. To be validated by her. */
  function recommend() {
    const a = answers;
    if (a.reason === "legs") return { main: "massage-drainant", alt: null };

    const time = Number(a.time);
    const sound = a.sound === "yes" || (a.sound === "maybe" && a.reason === "mind");
    const curious = a.sound === "maybe"; // not the main pick, but worth suggesting

    if (a.zone === "face") {
      if (sound && time >= 90) return { main: "visage-sonotherapie", alt: "soin-visage" };
      if (sound || curious) return { main: "soin-visage", alt: "visage-sonotherapie" };
      return { main: "soin-visage", alt: time >= 90 ? "corps-visage" : null };
    }

    if (a.zone === "body") {
      if (sound && time >= 90) return { main: "corps-sonotherapie", alt: "massage-relaxant" };
      return { main: "massage-relaxant", alt: sound || curious ? "corps-sonotherapie" : null };
    }

    // Both body and face
    if (time >= 120) return { main: "duo-corps-visage", alt: "corps-visage" };
    if (time >= 90) return { main: "corps-visage", alt: sound ? "corps-sonotherapie" : "duo-corps-visage" };
    return { main: "massage-relaxant", alt: "corps-visage" };
  }

  function el(tag, attrs = {}, html = "") {
    const node = document.createElement(tag);
    Object.entries(attrs).forEach(([k, v]) => node.setAttribute(k, v));
    if (html) node.innerHTML = html;
    return node;
  }

  function focusHeading() {
    const h = root.querySelector("h2");
    if (h) h.focus({ preventScroll: false });
  }

  function backButton() {
    const btn = el("button", { type: "button", class: "quiz-back" }, T.back);
    btn.addEventListener("click", () => {
      const last = history.pop();
      if (last) delete answers[last];
      if (last === "reason") delete answers.zone; // zone may have been set automatically
      render();
    });
    return btn;
  }

  function renderQuestion(key) {
    const q = T.questions[key];
    const n = history.length + 1;
    root.replaceChildren();
    root.append(el("p", { class: "quiz-progress" }, T.progress.replace("{n}", n).replace("{total}", totalQuestions())));
    root.append(el("h2", { class: "quiz-question", tabindex: "-1" }, q.q));
    const list = el("div", { class: "quiz-options" });
    q.options.forEach(([value, label]) => {
      const btn = el("button", { type: "button", class: "quiz-option" }, label);
      btn.addEventListener("click", () => {
        answers[key] = value;
        history.push(key);
        if (key === "reason" && value === "face") answers.zone = "face";
        render();
      });
      list.append(btn);
    });
    root.append(list);
    if (history.length) root.append(backButton());
  }

  function renderResult() {
    const { main, alt } = recommend();
    const t = data.treatments[main];
    root.replaceChildren();

    const card = el("div", { class: "quiz-result" });
    card.append(el("div", { class: "photo photo--arch" }, `<img src="${t.img}" alt="">`));
    const info = el("div");
    info.append(el("p", { class: "eyebrow" }, T.result_eyebrow));
    info.append(el("h2", { class: "quiz-question", tabindex: "-1" }, t.name));
    info.append(el("p", { class: "meta" }, t.meta));
    info.append(el("p", {}, t.short));
    const actions = el("div", { class: "button-group" });
    actions.append(el("a", { class: "button", href: t.book, target: "_blank", rel: "noopener" }, T.book));
    actions.append(el("a", { class: "button button--outline", href: t.details }, T.details));
    info.append(actions);
    card.append(info);
    root.append(card);

    if (alt) {
      const a = data.treatments[alt];
      root.append(el("p", { class: "quiz-alt" },
        `${T.alt} <a class="text-link" href="${a.details}">${a.name}</a> (${a.meta})`));
    }

    root.append(el("p", { class: "quiz-call muted" },
      `${T.call} <a class="text-link" href="${data.call}" target="_blank" rel="noopener">${T.call_btn}</a>`));

    const restart = el("button", { type: "button", class: "quiz-back" }, T.restart);
    restart.addEventListener("click", () => {
      Object.keys(answers).forEach((k) => delete answers[k]);
      history.length = 0;
      render();
    });
    root.append(backButton(), restart);
  }

  let first = true;
  function render() {
    const key = nextQuestion();
    if (key) renderQuestion(key);
    else renderResult();
    if (!first) focusHeading();
    first = false;
  }

  render();
})();
